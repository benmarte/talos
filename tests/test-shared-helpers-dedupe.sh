#!/usr/bin/env bash
# test-shared-helpers-dedupe.sh -- one shared copy of each duplicated helper (#1014).
#
# A refactor: behaviour does not change. By id:
#   AC1  the remote-URL helper maps https, ssh (scp-style and ssh://) and
#        enterprise-host URLs, with and without .git, to the owner/name the
#        old copies gave (and pipeline-meta.sh, which uses it, agrees)
#   AC2  the shared comment preamble gives the same login and last line, with and
#        without a cloud-session footer, and still drives a real program
#   AC3  the merged glob function matches the same paths as glob_re and glob_ere
#        did, as a compiled regex and as an ERE
#   AC4  the duplicates are gone (prose in the PR; the greps here pin it)
set -u
. "$(dirname "$0")/helpers.sh"
make_sandbox || exit 1

SCRIPTS="$TALOS_ROOT/scripts"

# ── AC1: remote URL -> owner/name ─────────────────────────────────────────────
. "$SCRIPTS/pipeline-paths.sh"
slug_case() {  # URL EXPECTED-OWNER/NAME
  assert_eq "$2" "$(_talos_remote_slug "$1" 2>/dev/null)" "AC1 remote $1 -> $2"
}
slug_case "https://github.com/acme/widget.git" "acme/widget"
slug_case "https://github.com/acme/widget" "acme/widget"
slug_case "git@github.com:acme/widget.git" "acme/widget"
slug_case "git@github.com:acme/widget" "acme/widget"
slug_case "ssh://git@github.com/acme/widget.git" "acme/widget"
slug_case "ssh://git@ghe.example.com:2222/acme/widget" "acme/widget"
slug_case "https://ghe.example.com/acme/widget.git" "acme/widget"
slug_case "http://ghe.example.com/acme/widget" "acme/widget"
slug_case "https://user:tok@ghe.example.com/acme/widget.git" "acme/widget"
slug_case "git@ghe.example.com:acme/widget.git" "acme/widget"
slug_case "https://github.com/acme/widget/" "acme/widget"
slug_case "/srv/git/widget.git" ""

# pipeline-meta.sh's slug is this helper cut to two segments: its repo-url agrees
# on every form, run in a repository whose origin is that URL.
meta_case() {  # URL EXPECTED-REPO-URL
  local d="$SANDBOX/meta-$((++_META_N))" got
  mkdir -p "$d" && git -C "$d" init -q && git -C "$d" remote add origin "$1" || { fail "AC1 meta fixture for $1"; return; }
  got="$(cd "$d" && bash "$SCRIPTS/pipeline-meta.sh" repo-url 2>/dev/null)"
  assert_eq "$2" "$got" "AC1 pipeline-meta.sh repo-url for $1"
}
_META_N=0
meta_case "git@github.com:acme/widget.git" "https://github.com/acme/widget"
meta_case "ssh://git@ghe.example.com/acme/widget.git" "https://ghe.example.com/acme/widget"
meta_case "https://ghe.example.com/acme/widget" "https://ghe.example.com/acme/widget"
meta_case "https://github.com/group/sub/widget.git" "https://github.com/sub/widget"

# ── AC2: the comment preamble ─────────────────────────────────────────────────
eval "$(sed -n "/^_TALOS_COMMENT_PY='/,/^'\$/p" "$SCRIPTS/talos.sh")"
eval "$(sed -n "/^_TALOS_COUNT_PY=/,/^'\$/p" "$SCRIPTS/talos.sh")"
COMMENT_PROG='
import json
FOOTER = "\n\n---\n\n" + FOOT
bare = "Looks good.\n<!-- talos:reviewed sha=abc -->"
for body in (bare, bare + FOOTER, bare + FOOTER.replace("\n", "\r\n"), "", "---\n\n" + FOOT):
    print(json.dumps([last_line(body), lines(body)]))
for c in ({"author": {"login": "bot"}}, {"author": None}, {"author": "bot"}, {}):
    print(json.dumps(login(c)))
'
GOT="$(python3 -I -c "$_TALOS_COMMENT_PY$COMMENT_PROG" 2>&1)"
WANT='["<!-- talos:reviewed sha=abc -->", ["Looks good.", "<!-- talos:reviewed sha=abc -->"]]
["<!-- talos:reviewed sha=abc -->", ["Looks good.", "<!-- talos:reviewed sha=abc -->"]]
["<!-- talos:reviewed sha=abc -->", ["Looks good.", "<!-- talos:reviewed sha=abc -->"]]
["", [""]]
["", [""]]
"bot"
null
null
null'
assert_eq "$WANT" "$GOT" "AC2 login and last line are the same with and without a cloud-session footer"

COMMENTS='{"comments": [{"author": {"login": "bot"}, "body": "x <!-- m -->\n\n---\n\n_Generated by [Claude Code](https://claude.ai/code)_"}, {"author": {"login": "eve"}, "body": "<!-- m -->"}, {"body": "<!-- m -->"}]}'
assert_eq "3" "$(python3 -I -c "$_TALOS_COUNT_PY" "<!-- m -->" 0 "" <<<"$COMMENTS" 2>&1)" "AC2 a program built on the preamble counts every marker when authors are not enforced"
assert_eq "1" "$(python3 -I -c "$_TALOS_COUNT_PY" "<!-- m -->" 1 "bot" <<<"$COMMENTS" 2>&1)" "AC2 a program built on the preamble counts only the trusted login when enforced"

# ── AC3: the merged glob function ─────────────────────────────────────────────
eval "$(sed -n "/^_GLOB_PY=/,/^'\$/p" "$SCRIPTS/pipeline-criteria.sh")"
GLOB_PROG='
import re
CASES = [
    ("tests/*.sh", "tests/a.sh", 1), ("tests/*.sh", "tests/sub/a.sh", 0), ("tests/*.sh", "tests/a.txt", 0),
    ("**/*.md", "README.md", 1), ("**/*.md", "docs/a/b.md", 1), ("**/*.md", "a.mdx", 0),
    ("src/**/x?.py", "src/x1.py", 1), ("src/**/x?.py", "src/a/b/x1.py", 1), ("src/**/x?.py", "src/x12.py", 0),
    ("a.b+c(d)", "a.b+c(d)", 1), ("a.b+c(d)", "aXb+c(d)", 0), ("a.b+c(d)", "a.b+c(d", 0),
    ("[x]|y$", "[x]|y$", 1), ("[x]|y$", "x", 0), ("**", "a/b", 0), ("*", "ab", 1),
]
for g, p, want in CASES:
    r = glob_re(g)
    e = glob_re(g, True)
    assert isinstance(e, str) and e.startswith("^") and e.endswith("$"), e
    print("%s\t%s\t%d\t%d\t%s" % (g, p, want, 1 if r.match(p) else 0, e))
'
GLOB_ROWS="$(python3 -I -c "import re$_GLOB_PY$GLOB_PROG" 2>&1)"
assert_eq "16" "$(grep -c . <<<"$GLOB_ROWS")" "AC3 the merged glob function ran every case"
while IFS=$'\t' read -r g p want re_got ere; do
  [ -n "$ere" ] || continue
  assert_eq "$want" "$re_got" "AC3 glob_re($g) on $p matches as before: $want"
  if [[ "$p" =~ $ere ]]; then ere_got=1; else ere_got=0; fi
  assert_eq "$want" "$ere_got" "AC3 glob_re($g, True) as an ERE on $p matches as before: $want"
done <<<"$GLOB_ROWS"

# ── AC4: the duplicates are gone ──────────────────────────────────────────────
assert_eq "1" "$(grep -c '^def login(c):' "$SCRIPTS/talos.sh")" "AC4 def login(c) exists once in talos.sh (inside the shared preamble)"
assert_eq "1" "$(grep -c '^FOOT = ' "$SCRIPTS/talos.sh")" "AC4 the cloud-footer constant exists once in talos.sh"
assert_eq "0" "$(grep -c 'glob_ere\|_printable\|_eval_repo\|_hooks_repo' "$SCRIPTS"/*.sh "$TALOS_ROOT/install.sh" | grep -vc ':0$')" "AC4 glob_ere, _printable, _eval_repo and _hooks_repo are gone"

finish
