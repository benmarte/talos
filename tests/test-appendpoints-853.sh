#!/usr/bin/env bash
# test-appendpoints-853.sh -- the shared append-points stop forcing a developer
# merge-base round (#853).
#
#   AC1 tests/check-defaults-table.py validates a defaults table with no row-count pin
#   AC3 two PRs that each add a config row, a CHANGELOG line, a timings change and
#       a regenerated docs table: the second is synced by pipeline-mergebase.sh
#   AC4 tests/timings.txt conflicts resolve to one line per basename
#   AC5 a docs/reference.md conflict outside the table block, a PR-changed generator
#       or a pipeline-defaults.sh conflict still exits 3, nothing pushed
#   AC6 any other conflicting path exits 3, alone or mixed with resolvable ones
#   AC8 the config loader ignores _note and _note_<key> leaves, nothing else
#   AC9 the shipped example has no line of 1000 bytes or more, prose in _note_<key>
#
# Each mergebase case builds a throwaway repo with a bare origin (no network),
# like tests/test-mergebase.sh.
set -u
. "$(dirname "$0")/helpers.sh"
make_sandbox
use_stubs

MB="$TALOS_ROOT/scripts/pipeline-mergebase.sh"
CHK="$TALOS_ROOT/tests/check-defaults-table.py"
