GEN="$TALOS_ROOT/tests/gen-config-table.py"
TAB="$(printf '\t')"
DELIM="TALOS_Fx7Qp2Lm9Ab"

# ── fixture helpers ──────────────────────────────────────────────────────────
# defaults_file <path> [<extra rows, newline separated>] writes a small
# pipeline-defaults.sh whose heredoc is a valid six-column table.
defaults_file() {
  local path="$1" extra="${2:-}" tail_extra="${3:-}"
  {
    printf '#!/usr/bin/env bash\n'
    printf "IFS= read -r -d '' _TALOS_DEFAULTS_RAW <<'%s' || true\n" "$DELIM"
    printf 'alpha.one\tstr\tx\t-\t-\tany\n'
    printf 'alpha.two\tint\t3\t-\t-\tany\n'
    printf 'mid.three\tbool\ttrue\t-\t-\tany\n'
    if [ -n "$extra" ]; then printf '%s\n' "$extra"; fi
    printf 'zeta.four\tstr\ty\t-\t-\trepo\n'
    if [ -n "$tail_extra" ]; then printf '%s\n' "$tail_extra"; fi
    printf '%s\n' "$DELIM"
  } > "$path"
}

# fx_new <name> -- a fresh repo + bare origin, seeded and pushed to main.
fx_new() {
  FXP="$SANDBOX/fx-$1"
  UP="$SANDBOX/fx-$1.git"
  mkdir -p "$FXP" || exit 1
  git init -q --bare "$UP"
  cd "$FXP" || exit 1
  git init -q -b main
  git config user.email "test@talos.invalid"
  git config user.name "talos-test"
  git remote add origin "$UP"
  mkdir -p scripts tests docs
  printf '# Changelog\n\n## [Unreleased]\n### Added\n- existing entry\n' > CHANGELOG.md
  printf '# Per-file wall seconds\n1 test-alpha.sh\n2 test-beta.sh\n3 test-gamma.sh\n' > tests/timings.txt
  cp "$GEN" tests/gen-config-table.py
  defaults_file scripts/pipeline-defaults.sh
  printf 'echo talos\n' > scripts/talos.sh
  printf '# Widget\n\nIntro line.\n' > README.md
  {
    printf '# Reference\n\nIntro text.\n\n'
    printf '<!-- config-table:start (generated by tests/gen-config-table.py; do not edit) -->\n\n<!-- config-table:end -->\n'
    printf '\nOutro text.\n'
  } > docs/reference.md
  python3 -I tests/gen-config-table.py --write docs/reference.md
  printf '{"vcs": {"provider": "github", "repo": "acme/widget"}, "base_branch": "main"}\n' > talos.pipeline.json
  git add -A
  git commit -qm "seed"
  git push -q origin main
}

# pr_branch <branch> <pr-n> -- run the mutator function named by $3 on a branch
# off origin/main, push it and its refs/pull/<n>/head, return to main.
pr_branch() {
  git fetch -q origin main
  git checkout -q -b "$1" origin/main
  "$3"
  git add -A
  git commit -qm "pr: $1"
  git push -q origin "$1"
  git push -q origin "$1:refs/pull/$2/head"
  git checkout -q main
  git branch -D "$1" >/dev/null 2>&1 || true
}

# base_commit <mutator> -- advance origin/main with the mutator's change.
base_commit() {
  git fetch -q origin main
  git checkout -q main
  git reset -q --hard origin/main
  "$1"
  git add -A
  git commit -qm "base: $1"
  git push -q origin main
}

# cl_add <text> -- add a CHANGELOG line right under "- existing entry".
cl_add() {
  awk -v t="$1" '{ print } /^- existing entry$/ { print t }' CHANGELOG.md > CHANGELOG.md.new && mv CHANGELOG.md.new CHANGELOG.md
}
regen() { python3 -I tests/gen-config-table.py --write docs/reference.md; }
mb() { STUB_PR_HEAD_REF_NAME="$1" bash "$MB" "$2" 2>&1; }

# ── AC1 the defaults-table check has no row-count pin ────────────────────────
D1="$SANDBOX/defaults-ok.sh"; defaults_file "$D1"
D2="$SANDBOX/defaults-extra.sh"; defaults_file "$D2" "extra.new${TAB}str${TAB}v${TAB}-${TAB}-${TAB}any"
D3="$SANDBOX/defaults-bad.sh"; defaults_file "$D3" "broken.row${TAB}str${TAB}v${TAB}-${TAB}any"
D4="$SANDBOX/defaults-dup.sh"; defaults_file "$D4" "alpha.one${TAB}str${TAB}z${TAB}-${TAB}-${TAB}any"

python3 -I "$CHK" "$D1" >/dev/null 2>&1; rc=$?
assert_eq "0" "$rc" "AC1 a valid defaults table passes"
python3 -I "$CHK" "$D2" >/dev/null 2>&1; rc=$?
assert_eq "0" "$rc" "AC1 an extra valid row needs no edit to any test (exit 0)"
out="$(python3 -I "$CHK" "$D3" 2>&1)"; rc=$?
assert_eq "1" "$rc" "AC1 a row with the wrong field count exits 1"
assert_contains "$out" "broken.row" "AC1 the malformed row is named"
out="$(python3 -I "$CHK" "$D4" 2>&1)"; rc=$?
assert_eq "1" "$rc" "AC1 a duplicate key exits 1"
assert_contains "$out" "alpha.one" "AC1 the duplicate key is named"
python3 -I "$CHK" "$TALOS_ROOT/scripts/pipeline-defaults.sh" >/dev/null 2>&1; rc=$?
assert_eq "0" "$rc" "AC1 the shipped defaults table passes"
assert_eq "0" "$(grep -c 'ROWS=' "$TALOS_ROOT/tests/test-config-defaults-table.sh")" "AC1 test-config-defaults-table.sh carries no ROWS= pin"

# ── AC3 two sibling PRs, each adding a key, a CHANGELOG line, timings and the docs table ──
fx_new ac3
pr3a() {
  defaults_file scripts/pipeline-defaults.sh "alpha.new_a${TAB}str${TAB}a${TAB}-${TAB}-${TAB}any"
  cl_add "- PR61 bullet"
  printf 'echo added by 61\n' > tests/test-added-by-61.sh
  printf '# Per-file wall seconds\n1 test-alpha.sh\n20 test-beta.sh\n3 test-gamma.sh\n5 test-pr61.sh\n' > tests/timings.txt
  regen
}
pr3b() {
  # PR 62's row goes last: a different spot from PR 61's.
  defaults_file scripts/pipeline-defaults.sh "" "zeta.new_b${TAB}str${TAB}b${TAB}-${TAB}-${TAB}any"
  cl_add "- PR62 bullet"
  printf '# Per-file wall seconds\n1 test-alpha.sh\n30 test-beta.sh\n3 test-gamma.sh\n6 test-pr62.sh\n' > tests/timings.txt
  regen
}
pr_branch pr-61 61 pr3a
pr_branch pr-62 62 pr3b
git fetch -q origin pr-61
git checkout -q main && git reset -q --hard origin/pr-61 && git push -q -f origin main
head62_before="$(git rev-parse origin/pr-62)"
out="$(mb pr-62 62)"; rc=$?
assert_eq "0" "$rc" "AC3 the second sibling PR is synced mechanically (exit 0)"
git fetch -q origin pr-62
assert_eq "$head62_before" "$(git rev-parse origin/pr-62^1)" "AC3 one merge commit was pushed on top of the PR head"
assert_eq "2" "$(git log -1 --format=%p origin/pr-62 | wc -w | tr -d ' ')" "AC3 the pushed commit is a merge"
git checkout -q --detach origin/pr-62
assert_eq "" "$(grep -rlE '^(<<<<<<<|>>>>>>>)' CHANGELOG.md tests/timings.txt docs/reference.md scripts/pipeline-defaults.sh)" "AC3 no conflict markers remain"
assert_contains "$(cat CHANGELOG.md)" "PR61 bullet" "AC3 CHANGELOG keeps the base's line"
assert_contains "$(cat CHANGELOG.md)" "PR62 bullet" "AC3 CHANGELOG keeps the PR's line"
assert_contains "$(cat scripts/pipeline-defaults.sh)" "alpha.new_a" "AC3 the defaults table has the base's row"
assert_contains "$(cat scripts/pipeline-defaults.sh)" "zeta.new_b" "AC3 the defaults table has the PR's row"
python3 -I tests/gen-config-table.py --check docs/reference.md; rc=$?
assert_eq "0" "$rc" "AC3 the docs table equals gen-config-table.py --check clean"
assert_contains "$(cat docs/reference.md)" "alpha.new_a" "AC3 the docs table lists the base's key"
assert_contains "$(cat docs/reference.md)" "zeta.new_b" "AC3 the docs table lists the PR's key"
assert_eq "20 test-beta.sh" "$(grep ' test-beta.sh' tests/timings.txt)" "AC3 the shared timings line takes the base's value"
assert_contains "$(cat tests/timings.txt)" "test-pr62.sh" "AC3 the PR's timings line is kept"
# run-tests.sh's count check names a test file the base has and the tree lacks as
# missing; the sync merge commit brings the base's new file in.
assert_file_exists "tests/test-added-by-61.sh" "AC3 the base's new test file is in the synced tree (the count check sees nothing missing)"
git checkout -q main

